"""Shared helpers for the paper's analysis scripts.

Every number the paper prints is registered here as a named value and written to ``paper/numbers.tex`` as

    \\ffdef{key}{value}

and used in the text as ``\\val{key}``. Tables are written to ``paper/tables/*.tex``. Nothing in ``paper/`` that a
script writes is meant to be edited by hand: rerun ``python paper/analysis/make_all.py`` instead.

Keys are lower-case letters, digits and hyphens. A value is LaTeX text-mode material (signs are written with
``\\ensuremath{-}`` / ``\\ensuremath{+}`` so a negative number never prints as a hyphen).
"""
from __future__ import annotations

import csv
