def official_str(v: float) -> str:
    """An official score as published: its own precision, at least four decimals (0.9620, 0.9613617)."""
    s = f"{v:.7f}".rstrip("0")
    whole, _, frac = s.partition(".")
    return f"{whole}.{frac.ljust(4, '0')}"


def offset_str(official: float, rehearsal: float, nd: int = 4) -> str:
    """official - rehearsal rounded HALF-UP from the exact decimal values (0.9712 - 0.96515 = 0.00605 -> +0.0061),
    the rule results/official-scores.csv uses. Binary floats would round 0.00605 down."""
    from decimal import ROUND_HALF_UP, Decimal
    d = (Decimal(repr(official)) - Decimal(repr(rehearsal))).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP)
    return num(float(d), nd, sign=True)


def binom_tail(k: int, n: int) -> float:
    """P(X >= k) for X ~ Binomial(n, 1/2): a one-sided sign test."""
    return sum(math.comb(n, i) for i in range(k, n + 1)) / 2.0 ** n


def _f(v: Optional[str]) -> Optional[float]:
    v = (v or "").strip()
    return float(v) if v else None


def load_scores() -> List[dict]:
    rows = []
    with open(SCORES, newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            rows.append({
                "name": r["submission"].strip(),
                "date": r["uploaded_cdt"].strip(),
                "chip": r["rehearsal_chip"].strip(),
                "rehearsal": _f(r["rehearsal_bpb"]),
                "steps": _f(r["rehearsal_steps"]),
                "official": _f(r["official_bpb"]),
                "best": r["best_so_far"].strip() == "yes",
                "note": r["change_vs_previous_best"].strip(),
            })
    return rows


