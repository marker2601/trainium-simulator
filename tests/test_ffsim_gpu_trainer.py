    for name in ("class _Relu2Fn(torch.autograd.Function):", "class _LeakySq(torch.autograd.Function):",
                 "class _FusedChunkedCE(torch.autograd.Function):", "class MuonAdamW(torch.optim.Optimizer):",
                 "def init_weights(self) -> None:", "def cooldown_level(progress: float) -> int:",
                 "def mtp_stage_of(progress: float) -> int:", "def accum_phase_of(next_step: int, progress: float) -> int:"):
        assert text.count(name) == 1 and source_text.count(name) == 1, name
    # the clock read is replaced exactly once, and every consumer of `charged` still reads `charged`
    assert text.count("charged = _GPU_VCLOCK.charged if _GPU_VCLOCK is not None else charged_wall") == 1
    assert "level_next = cooldown_level(charged / TIME_TARGET_SECONDS)" in text
    assert "mtp_stage_next = mtp_stage_of(charged / TIME_TARGET_SECONDS)" in text
    assert "step + 1, charged / TIME_TARGET_SECONDS if reached_min_steps else 0.0) if ACCUM_ON else 0" in text


