def test_strip_and_refuse_on_a_real_queue_env():
    overrides = REPO / "research" / "sim-data" / "chipC" / "1639_R_m14asa_s73" / "overrides"
    if not overrides.exists():
        pytest.skip("chip C overrides not harvested")
    env = gpu_env.parse_env_file(overrides.read_text(encoding="utf-8"))
    env.update({"NEURON_RT_STOCHASTIC_ROUNDING_EN": "0", "NEURON_COMPETITION_R1_CACHE_DIR": "/data", "FF_HOST_TIMES": "1"})
    kept, removed = gpu_env.strip(env)
    assert {"FF_CC_FLAGS", "FF_TIMEOUT", "NEURON_COMPETITION_R1_COMPILE", "NEURON_RT_STOCHASTIC_ROUNDING_EN", "FF_HOST_TIMES"} <= set(removed)
    assert {"FF_TIME_TARGET", "FF_EMA", "FF_SEED", "FF_ATTN_SRC", "NEURON_COMPETITION_R1_CACHE_DIR", "FF_MUON_ZERO2"} <= set(kept)
    assert removed["FF_COMPILE_SYNC"].startswith("strip:")               # FF_COMPILE_SYNC=0 on the chip: inert
    assert "FF_XU_QUEUE" in removed                                       # the queue env sets it (32): a Neuron runtime knob
    with pytest.raises(SystemExit) as ei:
        gpu_env.refuse(env)
    msg = str(ei.value)
    assert "FF_CC_FLAGS" in msg and "FF_HOST_TIMES" in msg and "NEURON_RT_STOCHASTIC_ROUNDING_EN" in msg
    assert "FF_TIMEOUT" not in msg and "FF_COMPILE_SYNC" not in msg     # tolerated, not refused
    gpu_env.refuse(kept)                                                  # what fleet passes on is accepted


