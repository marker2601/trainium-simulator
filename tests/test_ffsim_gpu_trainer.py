@needs_source
def test_every_patch_applies_exactly_once(built):
    text, report = built
    names = [r["name"] for r in report]
    assert len(names) == len(set(names)) and len(names) >= 30
    assert all(r["delta_chars"] != 0 or r["mode"] == "replace" for r in report)
    for p in make_train_gpu.build_patches("", "x") if False else []:  # (build_patches needs the source; see below)
        pass
    # the anchors of the replace/insert patches are gone or still there exactly as the mode says
    for p in make_train_gpu.build_patches(SOURCE.read_text(encoding="utf-8"), "submission/x/train.py"):
        if p.mode == "prepend":
            continue
        if p.mode == "replace" and p.anchor not in p.replacement:
            assert p.anchor not in text, p.name
        else:
            assert text.count(p.anchor) == p.count, p.name


