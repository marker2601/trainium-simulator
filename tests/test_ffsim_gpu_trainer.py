    text, _ = built
    compile(text, "train_gpu.py", "exec")
    sha = make_train_gpu.sha256_text(source_text)
    assert f'_GPU_SOURCE_SHA256 = "{sha}"' in text
    assert text.startswith("# GENERATED by ffsim/gpu/make_train_gpu.py")
    # neuron is refused at the device level and never a compile backend choice for the GPU
    assert 'raise SystemExit("train_gpu.py runs on cuda or cpu only' in text
