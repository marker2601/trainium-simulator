@needs_c40
def test_virtual_clock_reproduces_c40_switch_steps_within_2():
    log = vclock.parse_chip_log(str(C40_LOG))
    means = vclock.phase_seconds_from_log(str(C40_LOG))
    assert means[1] == pytest.approx(0.2968, abs=2e-4) and means[2] == pytest.approx(0.5102, abs=2e-4) \
        and means[4] == pytest.approx(0.9341, abs=2e-4)
    walk = vclock.walk_schedule(vclock.Recipe(), means)
    cmp = vclock.compare_schedules(walk, log)
    assert not cmp["missing"]
    assert cmp["max_abs_switch_diff"] <= 2, vclock.format_comparison(cmp)
    assert cmp["steps_diff"] == 0 and walk["stop_reason"] == "clock"
    assert walk["charged_final"] == pytest.approx(1787.1, abs=0.2)
    # the shipped default triple is the same C40 means
    walk_default = vclock.walk_schedule(vclock.Recipe(), vclock.DEFAULT_STEP_SECONDS)
    assert walk_default["steps"] == 2357 and walk_default["accum"] == walk["accum"]


@needs_c40
def test_medians_drift_late_switches_as_documented():
    log = vclock.parse_chip_log(str(C40_LOG))
    walk = vclock.walk_schedule(vclock.Recipe(), log["median_by_k"])
    cmp = vclock.compare_schedules(walk, log)
    # medians run 0.3-1% under the means: switches late by a few steps, the stop by ~0.5% (12 of 2357)
    assert 3 <= cmp["max_abs_switch_diff"] <= 15 and 5 <= cmp["steps_diff"] <= 20
    pinned = vclock.walk_schedule(vclock.Recipe(), log["median_by_k"], stop_step=2357)
    assert pinned["steps"] == 2357 and pinned["stop_reason"] == "stop_step"


@needs_c40
def test_rescale_to_steps_hits_the_target_and_keeps_fractions():
    means = vclock.phase_seconds_from_log(str(C40_LOG))
    r = vclock.Recipe()
    for target in (2361, 2340, 2314, 2200):
        scaled, scale, walk = vclock.rescale_to_steps(r, means, target)
        assert walk["steps"] == target and walk["stop_reason"] == "stop_step"
        # the clock-driven stop lands on the target too (the pin never truncates a longer schedule)
        assert vclock.walk_schedule(r, scaled)["steps"] == target
        assert scale == pytest.approx(2357 / target, rel=0.02)
        # switches sit at the same charged FRACTION: phase 2 at 6%, phase 3 / MTP stage 4 at 20%, level 19 at 40%
        assert walk["accum"][1][2] == pytest.approx(0.06 * 1793, abs=0.6)
        assert walk["accum"][2][2] == pytest.approx(0.20 * 1793, abs=1.0)
        assert walk["levels"][0][2] == pytest.approx(0.40 * 1793, abs=1.0)
        assert walk["final_level"] == 1
    with pytest.raises(ValueError):
        vclock.rescale_to_steps(r, means, 50)


