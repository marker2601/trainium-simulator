@pytest.mark.parametrize("shares", [8, 4, 2, 1])
def test_data_world_fetch_order_matches_an_explicit_rank_split(shares):
    ks = [4] * 20 + [1] * 30 + [2] * 30 + [4] * 12
    emulated = datasplit.emulated_fetch_order(ks, shares)
    reference = datasplit.trainium_step_rows(ks, shares)
    assert len(emulated) == len(ks)
    for step, (a, b) in enumerate(zip(emulated, reference)):
        assert len(a) == ks[step] * shares
        assert sorted(a) == sorted(b), step            # same rows per optimizer step
        assert a == sorted(a)                          # share by share, each share in its own order
    for s in range(shares):                            # every share's generator is consumed in order
        seq = [m for step in emulated for (sh, m) in step if sh == s]
        assert seq == list(range(len(seq)))


def test_share_cursor_rules():
    c = datasplit.ShareCursor(8, 4)
    assert [c.next_share() for _ in range(32)] == [j // 4 for j in range(32)]
    assert c.j == 0
    c.next_share()                     # the prefetched micro 0 of the next step (share 0 whatever k is)
    c.set_k(1)                         # allowed right after that prefetch
    assert [c.next_share() for _ in range(7)] == list(range(1, 8)) and c.j == 0
    c.next_share(); c.next_share()
    with pytest.raises(RuntimeError, match="mid-step"):
        c.set_k(4)
    with pytest.raises(ValueError):
        datasplit.ShareCursor(0, 4)


