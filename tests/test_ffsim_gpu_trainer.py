def test_walk_analytic_boundaries():
    # constant 1 s per step in every phase, TT 1000: k1 until 6% -> charged 60 -> after 15 warm-up + 45 k1 steps
    r = vclock.Recipe(time_target=1000.0)
    w = vclock.walk_schedule(r, {1: 1.0, 2: 1.0, 4: 1.0})
    assert w["accum"][0] == [1, 20, 15.0, 1]
    assert w["accum"][1][:2] == [2, 65]          # charged 60 reached after step 64 -> phase 2 from step 65
    assert w["accum"][2][:2] == [3, 205]         # 20% of 1000 = 200 s -> after step 204
    assert w["mtp"][0][:2] == [1, 55]            # 5% -> charged 50 -> after step 54
    assert w["levels"][0][:2] == [19, 405]       # cooldown starts at 40% -> 400 s -> after step 404
    # charged after step s is s - 4; stop when charged + est(1 s) + reserve(5 s) >= 1000 -> after step 998
    assert w["stop_reason"] == "clock" and w["steps"] == 999
    assert w["final_level"] == 1
    pinned = vclock.walk_schedule(r, {1: 1.0, 2: 1.0, 4: 1.0}, stop_step=500)
    assert pinned["steps"] == 500 and pinned["stop_reason"] == "stop_step" and pinned["levels"][-1][0] > 1


